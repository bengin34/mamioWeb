// Copies the App Store screenshot captions (eyebrow / lead / head per frame)
// from the mamio app repo, so the site describes each screenshot with the
// same reviewed wording the store uses.
//   node scripts/import-screen-copy.mjs [path/to/mamio]   (default: ../mamio)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const mamio = resolve(process.argv[2] ?? join(import.meta.dirname, '../../mamio'));
const dir = join(mamio, 'marketing/screenshots');
if (!existsSync(join(dir, 'hero-copy.json'))) {
  console.error(`No hero copy in ${dir}`);
  process.exit(1);
}

const copy = JSON.parse(readFileSync(join(dir, 'hero-copy.json'), 'utf8'));
delete copy._README;
for (const file of readdirSync(join(dir, 'hero-copy')).filter((f) => f.endsWith('.json'))) {
  copy[file.replace(/\.json$/, '')] = JSON.parse(readFileSync(join(dir, 'hero-copy', file), 'utf8'));
}

// hero-copy language key -> site code. Portugal reads the Brazilian copy;
// Swahili has no store listing, so it keeps the original site screens.
const siteCode = { 'pt-BR': 'pt-br', 'zh-Hans': 'zh-hans', 'zh-Hant': 'zh-hant' };
const out = {};
for (const [lang, frames] of Object.entries(copy)) {
  out[siteCode[lang] ?? lang] = frames.map(({ eyebrow, lead, head }) => ({ eyebrow, lead, head }));
}
if (out['pt-br'] && !out.pt) out.pt = out['pt-br'];

const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
writeFileSync(
  join(import.meta.dirname, '../src/app-screens-copy.js'),
  `// Generated by scripts/import-screen-copy.mjs from mamio/marketing/screenshots.\n// One entry per App Store screenshot frame, in file order (01_home ... 10_history).\nexport default ${JSON.stringify(sorted, null, 2)};\n`,
);
console.log(`${Object.keys(sorted).length} languages, ${sorted.en.length} frames each`);
