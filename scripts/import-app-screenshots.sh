#!/usr/bin/env bash
# Copies the composed App Store screenshots from the mamio app repo into the
# site, one folder per site language, resized to 736 px wide JPEGs.
#
#   scripts/import-app-screenshots.sh [path/to/mamio]     (default: ../mamio)
#
# Reads  <mamio>/marketing/screenshots-final/<store-locale>/NN_name.png
#        (made by mamio's scripts/compose-screenshots.mjs; gitignored there)
# Writes public/assets/app-screens/<site-code>/NN_name.jpg
#        src/app-screens.js     (which site languages have their own set)
#
# Needs macOS `sips`, or ImageMagick (`magick`) elsewhere.
set -euo pipefail

SITE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MAMIO_ROOT="$(cd "${1:-$SITE_ROOT/../mamio}" && pwd)"
SRC="$MAMIO_ROOT/marketing/screenshots-final"
OUT="$SITE_ROOT/public/assets/app-screens"
WIDTH=736

if [[ ! -d "$SRC" ]]; then
  echo "No $SRC. Run 'node scripts/compose-screenshots.mjs' in the mamio repo first." >&2
  exit 1
fi

if command -v sips >/dev/null; then
  convert_one() { sips -s format jpeg -s formatOptions 78 --resampleWidth "$WIDTH" "$1" --out "$2" >/dev/null; }
elif command -v magick >/dev/null; then
  convert_one() { magick "$1" -resize "${WIDTH}x" -strip -quality 78 "$2"; }
else
  echo "Need macOS sips or ImageMagick." >&2
  exit 1
fi

# site code -> store screenshot folder. pt (Portugal) uses the Brazilian set,
# sw has no store listing and falls back to English on the site.
pairs=(
  "en:en-US" "de:de-DE" "tr:tr" "es:es-ES" "fr:fr-FR" "it:it" "pt:pt-BR" "pt-br:pt-BR"
  "nl:nl-NL" "sv:sv" "pl:pl" "cs:cs" "ro:ro" "el:el" "ru:ru" "uk:uk" "ar:ar-SA" "he:he"
  "hi:hi" "bn:bn-BD" "th:th" "vi:vi" "id:id" "ja:ja" "ko:ko" "zh-hans:zh-Hans" "zh-hant:zh-Hant"
)

rm -rf "$OUT"
done_codes=()
for pair in "${pairs[@]}"; do
  code="${pair%%:*}"
  store="${pair#*:}"
  dir="$SRC/$store"
  if [[ ! -d "$dir" ]]; then
    echo "skip $code: no $store folder"
    continue
  fi
  mkdir -p "$OUT/$code"
  count=0
  for png in "$dir"/*.png; do
    [[ -e "$png" ]] || continue
    name="$(basename "$png" .png)"
    convert_one "$png" "$OUT/$code/$name.jpg"
    count=$((count + 1))
  done
  echo "$code <- $store: $count"
  done_codes+=("\"$code\"")
done

files=$(cd "$OUT/en" && ls *.jpg | sed 's/\.jpg$//' | sed 's/.*/"&"/' | paste -sd, -)
{
  echo '// Generated by scripts/import-app-screenshots.sh. Site languages with their own'
  echo '// screenshot set in public/assets/app-screens/<code>/, and the file names.'
  printf 'export default {\n  locales: [%s],\n  files: [%s],\n};\n' "$(IFS=,; echo "${done_codes[*]}")" "$files"
} > "$SITE_ROOT/src/app-screens.js"
du -sh "$OUT"
echo "Wrote src/app-screens.js. Commit public/assets/app-screens and src/app-screens.js."
